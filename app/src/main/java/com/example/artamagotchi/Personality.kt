/**
 * Выбирает реплики так, чтобы они не повторялись подряд:
 * помнит последние сказанные фразы и не берёт их снова, пока есть другие.
 */
class PhrasePicker(private val memory: Int = 14) {
    private val recent = ArrayDeque<String>()

    fun next(
        personality: Personality, situation: Situation, playerName: String,
        heroFemale: Boolean, playerFemale: Boolean
    ): String {
        val all = Phrases.of(personality, situation)
        val fresh = all.filter { it !in recent }
        // Если всё из этой ситуации уже звучало недавно — берём то, что звучало давнее всего
        val line = if (fresh.isNotEmpty()) fresh.random() else all.minByOrNull { recent.lastIndexOf(it) } ?: all.first()
        recent.remove(line)
        recent.addLast(line)
        while (recent.size > memory) recent.removeFirst()
        return line
            .replace(HERO_FORM) { it.groupValues[if (heroFemale) 2 else 1] }
            .replace(PLAYER_FORM) { it.groupValues[if (playerFemale) 2 else 1] }
            .replace("{p}", playerName)
    }

    private companion object {
        val HERO_FORM = Regex("\\{([^{}|]*)\\|([^{}|]*)\\}")
        val PLAYER_FORM = Regex("\\[([^\\[\\]|]*)\\|([^\\[\\]|]*)\\]")
    }
}
